#[derive(Debug, thiserror::Error)]
pub enum LocalError {
    #[error("“{0}” isn't a valid Hugging Face model id (expected owner/name)")]
    BadRepoId(String),
    #[error("no model called “{0}” on Hugging Face")]
    NotFound(String),
    #[error(
        "this model needs permission: accept its license on huggingface.co, then add your \
         Hugging Face token in Settings → Local engine"
    )]
    NeedsAccess,
    #[error("Hugging Face rejected the token (HTTP {0})")]
    BadToken(u16),
    #[error("couldn't reach {0}")]
    Network(String),
    #[error("HTTP {status} from {url}")]
    Http { status: u16, url: String },
    #[error("{0}")]
    Check(String),
    #[error("not enough free disk space: need {need_gb:.1} GB, have {have_gb:.1} GB")]
    DiskSpace { need_gb: f64, have_gb: f64 },
    #[error("{file} is damaged (checksum mismatch); it will be downloaded again next time")]
    Checksum { file: String },
    #[error("cancelled")]
    Cancelled,
    #[error("{context}: {source}")]
    Io {
        context: String,
        #[source]
        source: std::io::Error,
    },
    #[error("{0}")]
    Runtime(String),
}

impl LocalError {
    pub(crate) fn io(context: impl Into<String>) -> impl FnOnce(std::io::Error) -> LocalError {
        let context = context.into();
        move |source| LocalError::Io { context, source }
    }
}

/// Reads a child process's output line by line until it closes. Bytes that
/// aren't valid UTF-8 (Windows code pages) are replaced rather than ending the
/// read: stopping early would close the pipe and break the child's writes.
pub(crate) fn read_lines(
    stream: impl tokio::io::AsyncRead + Unpin + Send + 'static,
    mut on_line: impl FnMut(String) + Send + 'static,
) {
    use tokio::io::AsyncBufReadExt;
    tokio::spawn(async move {
        let mut reader = tokio::io::BufReader::new(stream);
        let mut buf = Vec::new();
        loop {
            buf.clear();
            match reader.read_until(b'\n', &mut buf).await {
                Ok(0) | Err(_) => break,
                Ok(_) => {
                    let line = String::from_utf8_lossy(&buf);
                    on_line(line.trim_end_matches(['\r', '\n']).to_string());
                }
            }
        }
    });
}

/// Environment for every Python process Chummy starts.
pub(crate) fn python_env(cmd: &mut tokio::process::Command) {
    cmd.env("PYTHONUTF8", "1")
        .env("PYTHONIOENCODING", "utf-8")
        .env("PYTHONNOUSERSITE", "1")
        .env("PYTHONDONTWRITEBYTECODE", "1")
        .env_remove("PYTHONPATH")
        .env_remove("PYTHONHOME");
}

/// Shared HTTP client settings.
pub(crate) fn http_client() -> reqwest::Client {
    chummy_http::builder()
        .connect_timeout(std::time::Duration::from_secs(15))
        .read_timeout(std::time::Duration::from_secs(60))
        .user_agent(concat!("Chummy/", env!("CARGO_PKG_VERSION")))
        .build()
        .expect("http client")
}
