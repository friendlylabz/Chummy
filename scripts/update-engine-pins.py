#!/usr/bin/env python3
"""Pins the built-in engine's downloads to their latest versions.

Writes crates/local/src/pins.rs, which Chummy uses when it installs the
engine's runtime:

- uv: the latest release, with the SHA-256 of each platform's download
  (from the .sha256 files uv publishes with every release);
- Python: the newest 3.12 patch release uv knows about (needs `uv` on PATH;
  otherwise the current pin is kept);
- PyTorch and the other packages: the latest version on PyPI, pinned with ==;
- a date for uv's --exclude-newer (today), so the dependencies of those
  packages can't pick up anything published after the pins were made.

Run it from anywhere, then build and test, and commit pins.rs:

    python3 scripts/update-engine-pins.py            # update to latest
    python3 scripts/update-engine-pins.py --check    # only show what would change

Uses only the standard library. Network: github.com and pypi.org.
"""

import argparse
import datetime
import json
import pathlib
import re
import shutil
import subprocess
import sys
import urllib.request

ROOT = pathlib.Path(__file__).resolve().parent.parent
PINS = ROOT / "crates" / "local" / "src" / "pins.rs"

UV_ASSETS = [
    "uv-x86_64-unknown-linux-gnu.tar.gz",
    "uv-aarch64-unknown-linux-gnu.tar.gz",
    "uv-x86_64-apple-darwin.tar.gz",
    "uv-aarch64-apple-darwin.tar.gz",
    "uv-x86_64-pc-windows-msvc.zip",
    "uv-aarch64-pc-windows-msvc.zip",
]
PYTHON_MINOR = "3.12"
TORCH = "torch"
PACKAGES = ["transformers", "accelerate", "safetensors", "jinja2", "sentencepiece", "protobuf"]
BITSANDBYTES = "bitsandbytes"


class NoRedirect(urllib.request.HTTPRedirectHandler):
    def redirect_request(self, *args, **kwargs):
        return None


def get(url: str) -> bytes:
    req = urllib.request.Request(url, headers={"User-Agent": "chummy-update-engine-pins"})
    with urllib.request.urlopen(req, timeout=60) as r:
        return r.read()


def latest_uv() -> str:
    """The latest uv release: where github.com/…/releases/latest points, or
    else the newest version tag (from git, for networks that block the page)."""
    opener = urllib.request.build_opener(NoRedirect)
    req = urllib.request.Request(
        "https://github.com/astral-sh/uv/releases/latest",
        headers={"User-Agent": "chummy-update-engine-pins"},
    )
    try:
        opener.open(req, timeout=60)
    except urllib.error.HTTPError as e:
        m = re.search(r"/releases/tag/([^/?#]+)$", e.headers.get("Location", "") or "")
        if m:
            return m.group(1)
    except OSError:
        pass
    out = subprocess.run(
        ["git", "ls-remote", "--tags", "--refs", "https://github.com/astral-sh/uv"],
        capture_output=True, text=True, check=True,
    ).stdout
    tags = [line.rsplit("/", 1)[-1] for line in out.splitlines()]
    tags = [t for t in tags if re.fullmatch(r"\d+\.\d+\.\d+", t)]
    if not tags:
        raise SystemExit("couldn't find uv's latest release")
    return max(tags, key=lambda t: tuple(int(x) for x in t.split(".")))


def uv_sha256(version: str, asset: str) -> str:
    text = get(f"https://github.com/astral-sh/uv/releases/download/{version}/{asset}.sha256").decode()
    sha = text.split()[0].lower()
    if not re.fullmatch(r"[0-9a-f]{64}", sha):
        raise SystemExit(f"bad checksum for {asset}: {text!r}")
    return sha


def pypi_latest(name: str) -> str:
    info = json.loads(get(f"https://pypi.org/pypi/{name}/json"))
    return info["info"]["version"]


def python_patch(current: str) -> str:
    uv = shutil.which("uv")
    if not uv:
        print("  (uv isn't on PATH: keeping Python", current + ")")
        return current
    out = subprocess.run(
        [uv, "python", "list", PYTHON_MINOR, "--only-downloads", "--output-format", "json"],
        capture_output=True, text=True, check=True,
    ).stdout
    versions = [
        v["version"] for v in json.loads(out)
        if v.get("implementation") == "cpython" and v.get("variant") in (None, "", "default") and v["version"].startswith(PYTHON_MINOR + ".")
        and re.fullmatch(r"\d+\.\d+\.\d+", v["version"])
    ]
    if not versions:
        return current
    return max(versions, key=lambda v: tuple(int(x) for x in v.split(".")))


def current_pins() -> dict:
    pins = {}
    if PINS.exists():
        text = PINS.read_text()
        for key in ["UV_VERSION", "PYTHON_VERSION", "EXCLUDE_NEWER"]:
            m = re.search(rf'pub const {key}: &str = "([^"]*)";', text)
            if m:
                pins[key] = m.group(1)
    return pins


def render(uv_version, uv_sums, python, torch, packages, bnb, date) -> str:
    assets = "\n".join(f'    ("{a}", "{s}"),' for a, s in uv_sums)
    pkgs = "\n".join(f'    "{p}",' for p in packages)
    return f'''//! Pinned versions of everything the built-in engine downloads.
//!
//! Generated by `scripts/update-engine-pins.py` on {date}: don't edit by hand,
//! run the script (it pins the latest versions), then build, test and commit.
//! uv is checked against these SHA-256 sums (never against sums downloaded
//! next to it); Python, PyTorch and the packages are exact versions; and
//! `EXCLUDE_NEWER` keeps the packages' own dependencies to releases from
//! before the pins were made.

/// The uv release Chummy downloads.
pub const UV_VERSION: &str = "{uv_version}";

/// SHA-256 of each platform's uv download.
pub const UV_ASSETS: &[(&str, &str)] = &[
{assets}
];

/// The private Python the runtime uses.
pub const PYTHON_VERSION: &str = "{python}";

/// PyTorch (uv picks the CUDA, CPU or Metal build of this version).
pub const TORCH: &str = "{torch}";

/// The other packages the engine needs.
pub const PACKAGES: &[&str] = &[
{pkgs}
];

/// For 8-bit and 4-bit loading on NVIDIA GPUs.
pub const BITSANDBYTES: &str = "{bnb}";

/// uv's `--exclude-newer` for the packages above (not PyTorch's own index,
/// which doesn't publish upload dates): nothing released after this.
pub const EXCLUDE_NEWER: &str = "{date}T23:59:59Z";
'''


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--check", action="store_true", help="show what would change, write nothing")
    ap.add_argument("--uv-version", help="pin this uv release instead of the latest")
    args = ap.parse_args()

    old = current_pins()
    print("Finding the latest versions…")
    uv_version = args.uv_version or latest_uv()
    print("  uv", uv_version)
    uv_sums = [(a, uv_sha256(uv_version, a)) for a in UV_ASSETS]
    python = python_patch(old.get("PYTHON_VERSION", PYTHON_MINOR + ".0"))
    print("  Python", python)
    torch = f"{TORCH}=={pypi_latest(TORCH)}"
    print(" ", torch)
    packages = []
    for p in PACKAGES:
        packages.append(f"{p}=={pypi_latest(p)}")
        print(" ", packages[-1])
    bnb = f"{BITSANDBYTES}=={pypi_latest(BITSANDBYTES)}"
    print(" ", bnb)
    date = datetime.datetime.now(datetime.timezone.utc).date().isoformat()

    text = render(uv_version, uv_sums, python, torch, packages, bnb, date)
    if args.check:
        same = PINS.exists() and PINS.read_text() == text
        print("No changes." if same else f"{PINS.relative_to(ROOT)} would change.")
        return
    PINS.write_text(text)
    print(f"Wrote {PINS.relative_to(ROOT)}. Build, test and commit it.")


if __name__ == "__main__":
    sys.exit(main())
